"""Build Tables 2a, 2b and 3 from results.csv alone, so every number can be recomputed from the raw file.

Definitions (state them in the write-up):
  * Percentiles: linear interpolation between closest ranks (numpy's default 'linear').
  * First token: over requests that released any reply text (answers, refusals, passages-only). Rows with an
    empty first_token_ms (gave up / busy with no text) are excluded and counted in the outcome columns instead.
  * Total time: over all requests. For someone who gave up, it's the time until they gave up.
  * Duration: from the first request's start to the last request's end.
  * Offered rate: requests / duration x 60.
  * Succeeded % = status ok. Rate-limited % = status rate_limited (including passages-only replies caused by a
    limit). Timed out or given up % = status timeout. Errors are the remainder (listed separately).
  * Peak queue length: requests in the system beyond the MAX_ACTIVE pipelines allowed to run at once, computed
    from start_time and total_ms.
  * Tokens per answer: mean tokens_in + tokens_out over status-ok requests.
  * Cost per 1,000 answers: the free tier costs $0. Shown at gpt-oss-120b list price ($0.15 / $0.60 per M tokens,
    from Groq's /models on 2026-11-09), i.e. if the same traffic ran on a paid plan with the largest model.
  * Table 3 uses only scenarios starting with "quality". The percentages are over graded rows.
"""
import csv
import datetime as dt
import math
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAX_ACTIVE = 12
PRICE_IN, PRICE_OUT = 0.15e-6, 0.60e-6


def pct(xs, p):
    xs = sorted(xs)
    if not xs:
        return None
    k = (len(xs) - 1) * p / 100
    f, c = math.floor(k), math.ceil(k)
    return xs[f] + (xs[c] - xs[f]) * (k - f)


def f0(x):
    return "n/a" if x is None else f"{x:.0f}"


def p3(xs):
    return " / ".join(f0(pct(xs, p)) for p in (50, 95, 99)) if xs else "not measured"


def p2(xs):
    return " / ".join(f0(pct(xs, p)) for p in (50, 95)) if xs else "not measured"


def ts(r):
    return dt.datetime.fromisoformat(r["start_time"]).timestamp()


def peak_queue(rows):
    ev = []
    for r in rows:
        s = ts(r)
        ev += [(s, 1), (s + float(r["total_ms"]) / 1000, -1)]
    cur = peak = 0
    for _, d in sorted(ev, key=lambda e: (e[0], e[1])):
        cur += d
        peak = max(peak, cur - MAX_ACTIVE)
    return max(0, peak)


def main():
    path = ROOT / "results.csv"
    if not path.exists():
        sys.exit("no results.csv yet")
    rows = list(csv.DictReader(path.open(encoding="utf-8")))
    by = defaultdict(list)
    for r in rows:
        by[r["scenario"]].append(r)
    out = ["# Results tables (generated by scripts/make_tables.py from results.csv)", "",
           f"{len(rows)} requests in results.csv. Definitions are in the make_tables.py docstring.", "",
           "## Table 2a: Latency", "",
           "| Scenario | Real or stand-in | Requests sent | Duration (s) | Offered rate (per min) | First token p50 / p95 / p99 (ms) | Total time p50 / p95 / p99 (ms) |",
           "|---|---|---|---|---|---|---|"]
    t2b = ["", "## Table 2b: Outcomes", "",
           "| Scenario | Succeeded % | Rate-limited % | Timed out or given up % | Retries per request | Peak queue length | Tokens per answer | Cost per 1,000 answers |",
           "|---|---|---|---|---|---|---|---|"]
    errs = []
    for scen, rs in by.items():
        if scen.startswith("quality"):
            continue
        n = len(rs)
        start = min(ts(r) for r in rs)
        end = max(ts(r) + float(r["total_ms"]) / 1000 for r in rs)
        dur = end - start
        ft = [float(r["first_token_ms"]) for r in rs if r["first_token_ms"]]
        tt = [float(r["total_ms"]) for r in rs]
        src = ", ".join(sorted({r["source"] for r in rs}))
        out.append(f"| {scen} | {src} | {n} | {dur:.0f} | {n / dur * 60:.1f} | {p3(ft)} | {p3(tt)} |")
        cnt = defaultdict(int)
        for r in rs:
            cnt[r["status"]] += 1
        ok = [r for r in rs if r["status"] == "ok"]
        tok = [int(r["tokens_in"]) + int(r["tokens_out"]) for r in ok]
        tin = sum(int(r["tokens_in"]) for r in ok) / max(1, len(ok))
        tout = sum(int(r["tokens_out"]) for r in ok) / max(1, len(ok))
        cost = (tin * PRICE_IN + tout * PRICE_OUT) * 1000
        retries = sum(int(r["retries"]) for r in rs) / n
        t2b.append(f"| {scen} | {100 * cnt['ok'] / n:.1f} | {100 * cnt['rate_limited'] / n:.1f} | "
                   f"{100 * cnt['timeout'] / n:.1f} | {retries:.2f} | {peak_queue(rs)} | "
                   f"{(sum(tok) / len(tok)) if tok else 0:.0f} | $0 free tier (${cost:.2f} at list price) |")
        if cnt["error"]:
            errs.append(f"{scen}: {100 * cnt['error'] / n:.1f}% error")
    out += t2b
    if errs:
        out += ["", "Errors (not one of the brief's columns): " + "; ".join(errs)]

    out += ["", "## Table 3: Retrieval settings", "",
            "| Setting (piece size, pieces fetched, re-rank yes or no) | Questions asked | Correct and cited % | Wrong % | Correctly refused % | Tokens per answer | First token p50 / p95 (ms) | Total time p50 / p95 (ms) |",
            "|---|---|---|---|---|---|---|---|"]
    q = defaultdict(list)
    for r in rows:
        if r["scenario"].startswith("quality"):
            q[r["retrieval_setting"]].append(r)
    if not q:
        out.append("| not measured yet | | | | | | | |")
    for setting, rs in q.items():
        g = [r["answer_grade"] for r in rs if r["answer_grade"]]
        n = len(g) or 1
        ok = [r for r in rs if r["status"] == "ok"]
        tok = [int(r["tokens_in"]) + int(r["tokens_out"]) for r in ok]
        ft = [float(r["first_token_ms"]) for r in rs if r["first_token_ms"]]
        tt = [float(r["total_ms"]) for r in rs]
        out.append(f"| {setting} | {len(rs)} | {100 * g.count('correct') / n:.1f} | {100 * g.count('wrong') / n:.1f} | "
                   f"{100 * g.count('refused_correctly') / n:.1f} | {(sum(tok) / len(tok)) if tok else 0:.0f} | {p2(ft)} | {p2(tt)} |")
    text = "\n".join(out) + "\n"
    (ROOT / "docs" / "tables.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
